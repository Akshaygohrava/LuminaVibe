// In-place Fisher-Yates shuffle helper
export function shuffleArray(arr) {
  const result = [...arr];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

// Combines backend stories and ensures the logged-in user's story is ALWAYS at index 0
export function getCuratedStories(currentUser, backendStories = []) {
  const userIdentifier = currentUser?.userId || currentUser?.user_id;
  const currentUsername = currentUser?.username ? currentUser.username.toLowerCase() : "";

  let userStory = null;
  const otherStories = [];

  backendStories.forEach(s => {
    const isSelf = (userIdentifier && s.userId === userIdentifier) ||
                   (currentUsername && s.username && s.username.toLowerCase() === currentUsername) ||
                   s.isSelf;
    if (isSelf) {
      userStory = {
        ...s,
        username: "Your story",
        isSelf: true
      };
    } else {
      // Enrich with overlay tips if matching known creator username
      const usernameKey = (s.username || "").toLowerCase();
      const insights = STORY_INSIGHTS[usernameKey] || [];
      const enrichedMedia = (s.mediaList || []).map((m, idx) => ({
        ...m,
        tag: m.tag || (insights[idx] ? insights[idx].tag : "Story Insight"),
        title: m.title || (insights[idx] ? insights[idx].title : ""),
        caption: m.caption || (insights[idx] ? insights[idx].caption : "")
      }));

      otherStories.push({
        ...s,
        mediaList: enrichedMedia
      });
    }
  });

  if (!userStory) {
    userStory = {
      id: 0,
      userId: userIdentifier || 9999,
      username: "Your story",
      avatar: currentUser?.profile_picture_url || currentUser?.profile_picture || "https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?w=150&auto=format&fit=crop",
      isSelf: true,
      mediaList: []
    };
  }

  return [userStory, ...otherStories];
}

// Combines and orders 100% REAL database posts:
// Real logged-in user's posts are STRICTLY PINNED TO THE TOP (newest first).
// All other real posts from PostgreSQL are dynamically shuffled on refresh/relogin for fresh variety!
export function getCuratedFeedPosts(currentUser, backendPosts = [], localUserPosts = []) {
  const userIdentifier = currentUser?.userId || currentUser?.user_id;
  const currentUsername = currentUser?.username ? currentUser.username.toLowerCase() : "";

  const isUserPost = (p) => {
    if (p.isSelf) return true;
    if (userIdentifier && p.user && (p.user.userId === userIdentifier || p.user.id === userIdentifier)) return true;
    if (currentUsername && p.user && p.user.username && p.user.username.toLowerCase() === currentUsername) return true;
    return false;
  };

  const realUserPosts = [];
  const otherRealPosts = [];
  const seenPostIds = new Set();

  // 1. Process backend database posts (100% real PostgreSQL rows)
  backendPosts.forEach(p => {
    const pId = String(p.id);
    if (!seenPostIds.has(pId)) {
      seenPostIds.add(pId);
      if (isUserPost(p)) {
        realUserPosts.push({ ...p, isSelf: true });
      } else {
        otherRealPosts.push({ ...p, isSelf: false });
      }
    }
  });

  // 2. Process optimistic session posts created by the current user
  localUserPosts.forEach(p => {
    const pId = String(p.id);
    if (!seenPostIds.has(pId)) {
      seenPostIds.add(pId);
      realUserPosts.unshift({ ...p, isSelf: true });
    }
  });

  // 3. Sort real user's posts by newest first
  realUserPosts.sort((a, b) => {
    const timeA = a.created_at ? new Date(a.created_at).getTime() : Date.now();
    const timeB = b.created_at ? new Date(b.created_at).getTime() : Date.now();
    return timeB - timeA;
  });

  // 4. Dynamically shuffle other real posts so every refresh/relogin feels alive
  const shuffledOthers = shuffleArray(otherRealPosts);

  // Real user posts ALWAYS strictly at the TOP, followed by dynamic mix of real community posts
  return [...realUserPosts, ...shuffledOthers];
}
